/**
 * Helper to get localized field note content
 */
export function getLocalizedNote(note, langId) {
  if (!note) return null;
  if (!langId || langId === 'en' || !note.locales || !note.locales[langId]) {
    return note;
  }

  const loc = note.locales[langId];
  return {
    ...note,
    title: loc.title || note.title,
    location: loc.location || note.location,
    region: loc.region || note.region,
    quote: loc.quote || note.quote,
    bodyText: loc.bodyText || note.bodyText,
    secondaryText: loc.secondaryText || note.secondaryText,
    custodian: {
      ...note.custodian,
      role: loc.custodianRole || note.custodian.role,
    },
    custodianBoundary: note.custodianBoundary ? {
      ...note.custodianBoundary,
      boundaryTitle: loc.boundaryTitle || note.custodianBoundary.boundaryTitle,
      reason: loc.boundaryReason || note.custodianBoundary.reason,
      explanation: loc.boundaryExplanation || note.custodianBoundary.explanation,
    } : note.custodianBoundary
  };
}
